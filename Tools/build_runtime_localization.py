"""Generate a small reviewed allowlist for UI strings embedded in mod DLLs."""

import hashlib
import json
from pathlib import Path

from lxml import etree as ET

from assembly_strings import user_strings
from combat_trade_sources import PROJECT, TARGETS


def main():
    data = json.loads((PROJECT / "Translations/RuntimeUI.json").read_text(encoding="utf-8"))
    actual = set()
    for path in (TARGETS["MeleeAnimation"] / "1.6/Assemblies/zAnimationMod.dll",
                 TARGETS["DynamicTradeInterface"] / "1.6/Assemblies/DynamicTradeInterface.dll",
                 PROJECT / "Components/SmartSpeed/Assemblies/SmartSpeed.dll",
                 PROJECT / "Components/InteractionBubbles/Assemblies/Bubbles.dll",
                 PROJECT / "Components/AlmostThere/Standard/Assemblies/CaravanDontRest.dll",
                 PROJECT / "Components/AlmostThere/Vehicles/Assemblies/CaravanDontRest.dll",
                 PROJECT / "Components/SnapOut/Assemblies/SnapOut.dll",
                 PROJECT / "Components/PickUpAndHaul/Assemblies/PickUpAndHaul.dll"):
        actual.update(user_strings(path))
    missing = set(data["literals"]) - actual
    if missing:
        raise ValueError(f"Literal absent from source assemblies: {missing!r}")
    rows = [(english, "TMM.Literal." + hashlib.sha256(english.encode()).hexdigest()[:12], russian)
            for english, russian in data["literals"].items()]
    for language, position in (("English", 0), ("Russian", 2)):
        root = ET.Element("LanguageData")
        for row in rows:
            ET.SubElement(root, row[1]).text = row[position]
        for name, russian in data["corpseOffsetModes"].items():
            ET.SubElement(root, f"TMM.CorpseOffset.{name}").text = name if language == "English" else russian
        path = PROJECT / f"Languages/{language}/Keyed/RuntimeUI.xml"
        path.parent.mkdir(parents=True, exist_ok=True)
        ET.ElementTree(root).write(str(path), encoding="utf-8", xml_declaration=True, pretty_print=True)
    lines = [
        "// Generated by Tools/build_runtime_localization.py from reviewed UI text.",
        "using System.Collections.Generic;", "namespace TurboMegaMod {",
        "internal static class RuntimeTranslationKeys {",
        "internal static readonly Dictionary<string, string> Literals = new Dictionary<string, string> {",
    ]
    for english, key, _ in rows:
        lines.append("{" + json.dumps(english, ensure_ascii=True) + "," + json.dumps(key) + "},")
    lines += ["};", "internal static readonly Dictionary<string, string> CorpseOffset = new Dictionary<string, string> {"]
    for name in data["corpseOffsetModes"]:
        lines.append("{" + json.dumps(name) + "," + json.dumps("TMM.CorpseOffset." + name) + "},")
    lines += ["};", "}", "}", ""]
    (PROJECT / "Source/RuntimeTranslationKeys.Generated.cs").write_text("\n".join(lines), encoding="utf-8")
    print(f"Prepared {len(rows)} embedded UI strings and {len(data['corpseOffsetModes'])} enum labels.")


if __name__ == "__main__":
    main()
